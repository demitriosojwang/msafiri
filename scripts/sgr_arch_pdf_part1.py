MAX_KEEP_HEIGHT = A4[1] * 0.4

def safe_keep_together(elements):
    total_h = 0
    for el in elements:
        try:
            w, h = el.wrap(CONTENT_W, A4[1])
            total_h += h
        except Exception:
            pass
    if total_h <= MAX_KEEP_HEIGHT:
        return [KeepTogether(elements)]
    elif len(elements) >= 2:
        return [KeepTogether(elements[:2])] + list(elements[2:])
    else:
        return list(elements)


_heading_counter = [0]
def _next_heading_id():
    _heading_counter[0] += 1
    return f'h_{_heading_counter[0]:04d}'


def H1(text):
    key = _next_heading_id()
    p = Paragraph(f'<a name="{key}"/>{text}', h1_style)
    p.bookmark_name = key
    p.bookmark_level = 0
    p.bookmark_text = text
    p.bookmark_key = key
    return p


