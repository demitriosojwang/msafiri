def Callout(text, kind='info'):
    color_map = {
        'info': SEM_INFO,
        'warning': SEM_WARNING,
        'success': SEM_SUCCESS,
        'error': SEM_ERROR,
    }
    border_color = color_map.get(kind, SEM_INFO)
    callout_local = ParagraphStyle(
        name='CalloutLocal', parent=callout_style,
        borderColor=border_color, borderWidth=0,
        backColor=SECTION_BG, borderPadding=8,
    )
    return Paragraph(text, callout_local)


def Table2(headers, rows, col_widths=None, caption=None):
    if col_widths is None:
        n = len(headers)
        col_widths = [CONTENT_W / n] * n

    cell_style = ParagraphStyle(
        name='Cell', fontName='FreeSerif', fontSize=9, leading=12,
        textColor=TEXT_PRIMARY, alignment=TA_LEFT,
    )
    header_cell_style = ParagraphStyle(
        name='HeaderCell', fontName='FreeSerif-Bold', fontSize=9, leading=12,
        textColor=colors.white, alignment=TA_LEFT,
    )

    data = [[Paragraph(str(h), header_cell_style) for h in headers]]
    for row in rows:
        data.append([Paragraph(str(c), cell_style) for c in row])

    t = Table(data, colWidths=col_widths, hAlign='CENTER', repeatRows=1)
    style_cmds = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('TEXTCOLOR', (0, 0), (-1, 0), TABLE_HEADER_TEXT),
        ('FONTNAME', (0, 0), (-1, 0), 'FreeSerif-Bold'),
        ('FONTSIZE', (0, 0), (-1, 0), 9),
        ('TOPPADDING', (0, 0), (-1, 0), 8),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 8),
        ('TOPPADDING', (0, 1), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 1), (-1, -1), 5),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('LINEBELOW', (0, 0), (-1, 0), 0.5, BORDER),
        ('LINEBELOW', (0, -1), (-1, -1), 0.5, BORDER),
    ]
    for i in range(1, len(data)):
        if i % 2 == 1:
            style_cmds.append(('BACKGROUND', (0, i), (-1, i), TABLE_ROW_ODD))
        else:
            style_cmds.append(('BACKGROUND', (0, i), (-1, i), TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style_cmds))

    elements = [Spacer(1, 6), t]
    if caption:
        elements.append(Paragraph(caption, caption_style))
    else:
        elements.append(Spacer(1, 12))
    return elements


