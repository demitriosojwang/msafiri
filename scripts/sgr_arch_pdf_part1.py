def _page_decoration(canv, doc):
    canv.saveState()
    canv.setStrokeColor(BORDER)
    canv.setLineWidth(0.4)
    canv.line(LEFT_M, 16 * mm, PAGE_W - RIGHT_M, 16 * mm)
    canv.setFont('FreeSerif', 8)
    canv.setFillColor(TEXT_MUTED)
    canv.drawString(LEFT_M, 11 * mm, 'SGR Feeder Platform — Architecture & Data Model Specification')
    canv.drawRightString(PAGE_W - RIGHT_M, 11 * mm, f'Page {doc.page}')
    canv.setStrokeColor(BORDER)
    canv.setLineWidth(0.3)
    canv.line(LEFT_M, PAGE_H - 14 * mm, PAGE_W - RIGHT_M, PAGE_H - 14 * mm)
    canv.setFont('FreeSerif-Italic', 8)
    canv.setFillColor(TEXT_MUTED)
    canv.drawString(LEFT_M, PAGE_H - 11 * mm, 'v1.0  ·  Engineering Reference')
    canv.drawRightString(PAGE_W - RIGHT_M, PAGE_H - 11 * mm, 'August 2026')
    canv.restoreState()
